//go:build windows

package storage

import (
	"os"

	"golang.org/x/sys/windows"
)

// openNoFollow opens path for reading without following a reparse point at
// its last component, sharing read, write and delete so that a reader never
// stops a writer or a removal (live-source reads in the design).
func openNoFollow(path string) (*os.File, error) {
	name, err := exclusiveWindowsPath(path)
	if err != nil {
		return nil, err
	}
	h, err := windows.CreateFile(name, windows.GENERIC_READ,
		windows.FILE_SHARE_READ|windows.FILE_SHARE_WRITE|windows.FILE_SHARE_DELETE, nil, windows.OPEN_EXISTING,
		windows.FILE_FLAG_OPEN_REPARSE_POINT|windows.FILE_FLAG_BACKUP_SEMANTICS, 0)
	if err != nil {
		return nil, &os.PathError{Op: "open", Path: path, Err: err}
	}
	return os.NewFile(uintptr(h), path), nil
}
