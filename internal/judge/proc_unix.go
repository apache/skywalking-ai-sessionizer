//go:build !windows

package judge

import (
	"os/exec"
	"syscall"
)

// ownGroup starts a command in a process group of its own, and makes a
// cancel kill the whole group. An agent CLI starts children of its own, such
// as the MCP server it runs, and a child left alive would hold the output
// pipes open after the CLI itself was killed.
func ownGroup(cmd *exec.Cmd) {
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	cmd.Cancel = func() error {
		if cmd.Process == nil {
			return nil
		}
		return syscall.Kill(-cmd.Process.Pid, syscall.SIGKILL)
	}
}
